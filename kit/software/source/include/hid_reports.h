inline void keyboard(const core::Action &action, uint8_t (&out)[8]) {
  for (auto &byte : out)
    byte = 0;
  out[0] = action.modifiers;
  out[2] = static_cast<uint8_t>(action.usage);
}
inline void consumer(const core::Action &action, uint8_t (&out)[2]) {
  out[0] = action.usage & 0xff;
  out[1] = action.usage >> 8;
}
